import {chromium} from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const nav=async v=>page.locator(`button[data-action="nav"][data-view="${v}"]`).first().click();
const command=async id=>{await page.locator(`[data-action="flight-command"][data-id="${id}"]`).click();await page.locator('[data-experience="skip"]').click();};
const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('hail-mary:v1')));
try{
 await page.goto('http://localhost:4173');
 await page.locator('[data-action="select-mission"][data-id="lander"]').click();await nav('builder');await page.locator('[data-action="launch"]').click();
 assert.ok(await page.locator('body.flight-game').count());
 await page.screenshot({path:'artifacts/game-flight.png',fullPage:true});
 for(const id of ['depart','precision','repair'])await command(id);
 await page.locator('[data-action="flight-command"][data-id="skip-arrival"]').click();
 await page.locator('[data-experience="speed"]').click();await page.locator('[data-experience="speed"]').click();
 await page.waitForFunction(()=>{const n=Number(document.querySelector('#maneuver-percent')?.textContent.replace('%',''));if(n>=70&&n<100){document.querySelector('[data-experience="pause"]').click();return true;}return false;});
 assert.match(await page.locator('#scene-caption').textContent(),/Impact confirmed/);
 await page.locator('#flight-cinema').screenshot({path:'artifacts/game-impact.png'});
 await page.locator('[data-experience="skip"]').click();
 assert.match(await page.locator('.game-result').textContent(),/MISSION FAILEDSurface impact/);
 assert.equal((await saved()).flight.outcome,'impact');
 await page.reload();await nav('flight');assert.match(await page.locator('.game-result').textContent(),/Surface impact/);
 await page.locator('[data-action="retry-flight"]').click();assert.equal((await saved()).flight.step,0);assert.equal((await saved()).archive.length,1);
 await command('depart');await page.keyboard.press('3');await page.locator('[data-experience="skip"]').click();
 assert.match(await page.locator('.game-result').textContent(),/Trajectory lost/);
 await page.locator('[data-action="retry-flight"]').click();
 for(const id of ['depart','precision','repair','arrive','relay'])await command(id);
 assert.match(await page.locator('.game-result').textContent(),/MISSION SUCCESSTouchdown confirmed/);
 await page.screenshot({path:'artifacts/game-success.png',fullPage:true});
 const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();assert.deepEqual(audit.violations.map(v=>v.id),[]);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.locator('[data-action="retry-flight"]').click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'artifacts/game-mobile.png',fullPage:true});
 await nav('builder');assert.equal(await page.locator('body.flight-game').count(),0);
 assert.deepEqual(errors,[]);console.log('Impact, escape, success, keyboard, reload, retry, mobile and accessibility checks passed.');
}finally{await browser.close();}
