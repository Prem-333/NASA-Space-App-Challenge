import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
page.on('pageerror',e=>console.error('PAGE ERROR:',e.message));
await page.goto('http://localhost:4173');
await page.evaluate(()=>document.fonts.ready);
await page.waitForTimeout(1500);
await page.screenshot({path:'artifacts/desktop-briefing.png',fullPage:true});
await page.locator('[data-action="nav"][data-view="builder"]').first().click();
await page.screenshot({path:'artifacts/desktop-builder.png',fullPage:true});
console.log('Desktop overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/mobile-builder.png',fullPage:true});
await page.locator('button[data-action="nav"][data-view="briefing"]').first().click();
await page.screenshot({path:'artifacts/mobile-briefing.png',fullPage:true});
console.log('Mobile overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await browser.close();
